"""Regenerate docs/families.md from the code: every family's card, and every template's protocol and counts.

    python scripts/make_docs.py
"""

from collections import Counter
from pathlib import Path

import cvtestbed as cvt

OUT = Path(__file__).resolve().parents[1] / "docs" / "families.md"


def main() -> None:
    fams = cvt.families()
    tmpl = cvt.templates()
    lines = ["# Families", "", "Generated by `scripts/make_docs.py` from the code; do not edit by hand.", ""]
    by_stream: dict[str, list[str]] = {}
    for name, f in fams.items():
        by_stream.setdefault(f.stream or "other", []).append(name)
    for stream in sorted(by_stream):
        lines += [f"## {stream[0].upper() + stream[1:]}", ""]
        for name in by_stream[stream]:
            f = fams[name]
            lines += [f"### `{name}`: {f.title}", "", f"*Tier {f.tier}; labelling cost: {f.cost}.*", "", f.card, ""]
            if name in tmpl:
                t = tmpl[name]
                c = Counter(q.status for q in t.questions())
                lines += [f"- **Protocol.** {t.setup or 'See the question text.'}",
                          f"- **Metric.** {t.metric}."]
                if t.style == "pairwise":
                    grid = "; ".join(f"{k}: {', '.join(map(str, v))}" for k, v in t.factors.items())
                    lines += [f"- **Design.** All combinations of {grid} ({len(t.design())} conditions). Questions "
                              "compare two conditions differing in one factor; void if the metrics differ by less "
                              f"than {t.min_gap:g}."]
                else:
                    lines += [f"- **Design.** {t.n_planned} sampled conditions plus earlier measurements; each "
                              f"question is a yes/no claim about one condition. {t.void_rule}"]
                lines += [f"- **Questions.** {c['labelled']} labelled, {c['void']} void, {c['unlabelled']} unlabelled "
                          f"(version {t.version}).", ""]
    OUT.write_text("\n".join(lines))
    print(OUT)


if __name__ == "__main__":
    main()
